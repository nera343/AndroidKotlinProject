package Kotlin

fun main() {
    // Deklarasi variabel sesuai tipe data
    val nama: String = "Andi Saputra"
    val umur: Int = 19
    val tinggiBadan: Double = 168.5
    val mahasiswaAktif: Boolean = true
    val golonganDarah: Char = 'B'

    // Output ke layar
    println("Nama            : $nama")
    println("Umur            : $umur tahun")
    println("Tinggi badan    : $tinggiBadan cm")
    println("Mahasiswa aktif : $mahasiswaAktif")
    println("Golongan darah  : $golonganDarah")
}
